import * as fs from 'node:fs';
import * as path from 'node:path';
import { spawnSync } from 'node:child_process';
import { Files, run } from './files.ts';
import type { Profile } from './install.ts';
import { readMachine } from './state.ts';

const timer = 'mise-prune.timer';
// Homebrew's prefixes are absent from launchd's default PATH.
const launchdPath = '/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin';

function escape(text: string) {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function plist(label: string, script: string, schedule: string) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by the CLI's mise component. Edit scripts/lib/mise.ts, then apply that component again. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/sh</string>
    <string>-c</string>
    <string>${escape(script)}</string>
  </array>
${schedule}
</dict>
</plist>
`;
}

export const vitePlusScopes: readonly string[] = ['node', 'npm', 'pnpm', 'yarn', 'bun'];

export function vitePlusHome(home: string) {
  return process.env.VP_HOME || path.join(home, '.vite-plus');
}

// Reports a Vite+ shim scope's mode, such as managed or system_first.
function vitePlusMode(vp: string, scope: string) {
  const result = spawnSync(vp, ['env', 'current', scope, '--json'], { encoding: 'utf8' });
  if (result.error || result.status !== 0) return undefined;
  try {
    const value: unknown = JSON.parse(result.stdout);
    const entry = isRecord(value) ? value[scope === 'node' ? 'node' : 'package_manager'] : undefined;
    return isRecord(entry) && typeof entry.mode === 'string' ? entry.mode : undefined;
  } catch {
    return undefined;
  }
}

export type MiseTool = { version: string, requested?: string, source?: string, installed: boolean };

// The tools mise selects in a directory, from `mise ls --current --json`. An
// entry without a version or installed flag is rejected rather than guessed at,
// so a changed format cannot make every tool look installed.
export function miseCurrent(directory: string): Record<string, MiseTool[]> {
  const result = spawnSync('mise', ['ls', '--current', '--json'], { cwd: directory, encoding: 'utf8' });
  if (result.error || result.status !== 0) throw new Error(`mise ls failed: ${result.error?.message ?? result.stderr.trim().split('\n').at(-1) ?? result.status}`);
  let value: unknown;
  try {
    value = JSON.parse(result.stdout);
  } catch {
    throw new Error('mise ls returned invalid JSON; run mise doctor');
  }
  if (!isRecord(value)) throw new Error('mise ls returned an unexpected shape');
  const text = (field: unknown) => typeof field === 'string' ? field : undefined;
  return Object.fromEntries(Object.entries(value).map(([tool, versions]) => {
    if (!Array.isArray(versions)) throw new Error(`mise ls returned an unexpected entry for ${tool}`);
    return [tool, versions.map(version => {
      if (!isRecord(version) || typeof version.version !== 'string' || typeof version.installed !== 'boolean') {
        throw new Error(`mise ls returned an unexpected entry for ${tool}`);
      }
      return {
        version: version.version, requested: text(version.requested_version),
        source: isRecord(version.source) ? text(version.source.path) : undefined, installed: version.installed,
      };
    })];
  }));
}

// The fragments linked into ~/.config/mise/conf.d. Omarchy's agent CLI wrappers
// run `mise use -g`, which refuses a tool two global files declare, so the agent
// CLIs Omarchy installs itself are only in the macOS fragment.
export function miseFragments(repo: string, profile: Profile) {
  return [path.join(repo, 'shared/mise/conf.d/donnes.toml'),
    ...profile === 'macos' ? [path.join(repo, 'macos/mise/conf.d/donnes-macos.toml')] : []];
}

export function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

export class Mise {
  constructor(private files: Files, private profile: Profile) {}

  private agents() {
    const helper = path.join(this.files.repo, 'macos/bin/xcode-node-env');
    const log = path.join(this.files.home, 'Library/Logs/dev.dstech.mise-prune.log');
    return [
      // GUI apps such as Xcode and Android Studio start with launchd's PATH, not
      // the shell's. The shims select each project's tool versions from its cwd;
      // opencode v2 comes from its own installer.
      ['dev.dstech.guipath', plist('dev.dstech.guipath',
        `/bin/launchctl setenv PATH "$HOME/.opencode/bin:$HOME/.local/share/mise/shims:/opt/homebrew/bin:/opt/homebrew/sbin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"`,
        '  <key>RunAtLoad</key>\n  <true/>')],
      // Repoint Xcode at the Node shim before pruning removes recorded install
      // paths. A sweep that fails skips the prune, which can wait a day.
      ['dev.dstech.mise-prune', plist('dev.dstech.mise-prune',
        `export PATH="${launchdPath}"; "${helper}" && exec mise prune --yes`,
        `  <key>StartCalendarInterval</key>\n  <dict>\n    <key>Hour</key>\n    <integer>12</integer>\n    <key>Minute</key>\n    <integer>30</integer>\n  </dict>\n  <key>StandardOutPath</key>\n  <string>${escape(log)}</string>\n  <key>StandardErrorPath</key>\n  <string>${escape(log)}</string>`)],
    ] as const;
  }

  private generated(label: string) {
    return path.join(this.files.repo, '.generated/launchd', `${label}.plist`);
  }

  private launchctl(args: string[], required = true) {
    if (required) run('launchctl', args);
    else spawnSync('launchctl', args, { stdio: 'ignore' });
  }

  private async macos(uninstall: boolean) {
    const uid = process.getuid?.();
    if (uid === undefined) throw new Error('launchd agents need a POSIX user id');
    const domain = `gui/${uid}`;
    for (const [label, content] of this.agents()) {
      const generated = this.generated(label);
      const destination = path.join(this.files.home, 'Library/LaunchAgents', `${label}.plist`);
      if (uninstall) {
        if (this.files.target(destination) !== generated) continue;
        this.files.log('unload', `launchd agent ${label}`);
        if (!this.files.dryRun) this.launchctl(['bootout', `${domain}/${label}`], false);
        this.files.unlink(generated, destination);
        continue;
      }
      const identical = fs.existsSync(generated) && fs.readFileSync(generated, 'utf8') === content;
      this.files.log(identical ? 'skip' : 'compose', `${this.files.pretty(generated)} launchd agent`);
      if (!this.files.dryRun && !identical) {
        fs.mkdirSync(path.dirname(generated), { recursive: true });
        fs.writeFileSync(generated, content);
      }
      await this.files.link(generated, destination, false, this.files.dryRun ? content : undefined);
      if (this.files.target(destination) !== generated && !this.files.dryRun) continue;
      this.files.log('load', `launchd agent ${label}`);
      if (!this.files.dryRun) {
        // Bootstrap fails while the agent is loaded, so reload it to pick up changes.
        this.launchctl(['bootout', `${domain}/${label}`], false);
        this.launchctl(['bootstrap', domain, destination]);
      }
    }
  }

  // Omarchy's config.toml sets its own idiomatic version file list, which replaces
  // the shared one. Append the missing tools through mise instead of editing it.
  private idiomatic(fragment: string) {
    const setting = 'idiomatic_version_file_enable_tools';
    const wanted = fs.readFileSync(fragment, 'utf8').match(new RegExp(`^${setting} = \\[(.*)\\]`, 'm'))?.[1]?.match(/[\w-]+/g) ?? [];
    const current = spawnSync('mise', ['settings', 'get', setting], { encoding: 'utf8' }).stdout ?? '';
    for (const tool of wanted.filter(tool => !current.includes(`"${tool}"`))) {
      this.files.log('setting', `mise settings add ${setting} ${tool}`);
      if (!this.files.dryRun) run('mise', ['settings', 'add', setting, tool]);
    }
  }

  // Vite+ puts node, npm, pnpm, yarn and bun shims ahead of mise on PATH. In its
  // default managed mode they run Vite+'s own runtimes, and a `vp env use`
  // session override outranks project pins. System-first mode hands each to the
  // next one on PATH, mise's, so terminals, agents and Xcode agree; `vp` stays.
  // machine.json's jsRuntimes can give them to Vite+ instead; either way the
  // shims are set to match it.
  private vitePlus() {
    const vp = path.join(vitePlusHome(this.files.home), 'bin/vp');
    if (!fs.existsSync(vp)) return;
    const owner = readMachine(this.files.home)?.jsRuntimes ?? 'mise';
    const [mode, command, runtimes] = owner === 'mise' ? ['system_first', 'off', 'mise'] : ['managed', 'on', 'Vite+'];
    const other = vitePlusScopes.filter(scope => vitePlusMode(vp, scope) !== mode);
    if (!other.length) { this.files.log('skip', `Vite+ hands ${vitePlusScopes.join(', ')} to ${runtimes}`); return; }
    this.files.log('setting', `vp env ${command} (${other.join(', ')} should use ${runtimes}'s runtimes)`);
    if (!this.files.dryRun) run(vp, ['env', command]);
  }

  private async omarchy(uninstall: boolean) {
    const units = path.join(this.files.home, '.config/systemd/user');
    if (uninstall) {
      this.files.log('disable', `systemd user timer ${timer}`);
      if (!this.files.dryRun) spawnSync('systemctl', ['--user', 'disable', '--now', timer], { stdio: ['inherit', 'inherit', 'ignore'] });
    }
    for (const unit of ['mise-prune.service', timer]) {
      const source = path.join(this.files.repo, 'omarchy/mise', unit), destination = path.join(units, unit);
      if (uninstall) this.files.unlink(source, destination);
      else await this.files.link(source, destination);
    }
    if (!uninstall) this.files.log('enable', `systemd user timer ${timer}`);
    if (!this.files.dryRun) {
      run('systemctl', ['--user', 'daemon-reload']);
      if (!uninstall) run('systemctl', ['--user', 'enable', '--now', timer]);
    }
  }

  async apply(uninstall: boolean) {
    for (const fragment of miseFragments(this.files.repo, this.profile)) {
      const destination = path.join(this.files.home, '.config/mise/conf.d', path.basename(fragment));
      if (uninstall) this.files.unlink(fragment, destination);
      else await this.files.link(fragment, destination);
    }
    if (this.profile === 'omarchy' && !uninstall) this.idiomatic(path.join(this.files.repo, 'shared/mise/conf.d/donnes.toml'));
    if (!uninstall) this.vitePlus();
    await (this.profile === 'macos' ? this.macos(uninstall) : this.omarchy(uninstall));
  }
}
